"""Load, inspect and clean the UCI Cleveland Heart Disease data (no external rows added)."""
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "processed.cleveland.data"
PROCESSED = ROOT / "data" / "processed" / "cleveland_clean.csv"
REPORT = ROOT / "outputs" / "data_quality_report.md"

COLUMNS = ["age", "sex", "cp", "trestbps", "chol", "fbs", "restecg", "thalach",
           "exang", "oldpeak", "slope", "ca", "thal", "num"]
NUMERIC = ["age", "trestbps", "chol", "thalach", "oldpeak", "ca"]
CATEGORICAL = ["sex", "cp", "fbs", "restecg", "exang", "slope", "thal"]
FEATURES = NUMERIC + CATEGORICAL
TARGET = "target"


def load_raw(path=RAW):
    """Read the raw file; '?' is the dataset's missing-value marker."""
    return pd.read_csv(path, header=None, names=COLUMNS, na_values="?")


def clean(raw):
    """Binary target (num > 0 -> 1). Rows are kept; imputation happens inside the
    model pipelines (fit on training folds only) to avoid leakage."""
    df = raw.copy()
    df[TARGET] = (df["num"] > 0).astype(int)
    return df.drop_duplicates().reset_index(drop=True)


def quality_report(raw, df):
    miss = raw.isna().sum()
    lines = [
        "# Data quality report (generated by src/prepare_data.py)", "",
        "Source: UCI Heart Disease, Cleveland subset (processed.cleveland.data). "
        "Detrano et al.; DOI 10.24432/C52P4X; CC BY 4.0.", "",
        f"- Records before cleaning: **{len(raw)}**",
        f"- Records after cleaning: **{len(df)}** (no rows dropped; duplicates removed: {len(raw) - len(df)})",
        f"- Columns: {len(raw.columns)}", "",
        "## Missing values ('?' in the raw file)", "",
    ]
    lines += [f"- {c}: {int(n)}" for c, n in miss.items() if n > 0] or ["- none"]
    lines += ["", f"Rows with any missing value: {int(raw.isna().any(axis=1).sum())}. "
              "These are imputed inside the pipeline (median numeric, most-frequent categorical).", "",
              "## Original diagnosis column (num)", ""]
    lines += [f"- num={k}: {v}" for k, v in raw["num"].value_counts().sort_index().items()]
    vc = df[TARGET].value_counts().sort_index()
    lines += ["", "## Binary target (0 = no angiographic disease, 1 = num > 0)", "",
              f"- 0: {vc.get(0, 0)} ({vc.get(0, 0) / len(df):.1%})",
              f"- 1: {vc.get(1, 0)} ({vc.get(1, 0) / len(df):.1%})", "",
              "## Column dtypes (after loading)", ""]
    lines += [f"- {c}: {t}" for c, t in raw.dtypes.items()]
    return "\n".join(lines) + "\n"


def main():
    raw = load_raw()
    df = clean(raw)
    PROCESSED.parent.mkdir(parents=True, exist_ok=True)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(PROCESSED, index=False)
    REPORT.write_text(quality_report(raw, df))
    print(f"raw={len(raw)} clean={len(df)} target={df[TARGET].value_counts().to_dict()}")
    return df


if __name__ == "__main__":
    main()
